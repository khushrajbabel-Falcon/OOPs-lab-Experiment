#include <iostream>
using namespace std;

int main()
{
    // Variables and data types
    int a = 10, b = 5;
    float F = 2.5;
    char C = 'A';

    // Constant
    const int x = 20;

    // Output
    cout << "a+b = " << a + b << endl;
    cout << "a-b = " << a - b << endl;
    cout << "a*b = " << a * b << endl;
    cout << "a/b = " << a / b << endl;

    cout << "Float = " << F << endl;
    cout << "Character = " << C << endl;
    cout << "Constant = " << x << endl;

    return 0;
}
